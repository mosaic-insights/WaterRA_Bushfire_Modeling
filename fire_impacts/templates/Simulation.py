# %% [markdown]
# ## Rainfall data
#
# Both the erosion (RUSLE) and debris flow modules rely on subdaily rainfall data. The erosion modules, demonstrated here, rely on 30 minute data, while the debris flow relies on 12 minute data.
#
# Furthermore, it is encouraged that both modules be run stochastically, using multiple rainfall replicates.
#
# The library provides functionality for processing stochastic rainfall data, generated by [pyraingen](https://github.com/crdykman/pyraingen). You can install pyraingen locally and calibrate it to available subdaily rainfall observations. Alternatively, you can call a remote pyraingen API and generate data based on publicly available data. We wil use the remote API in this example.

# %%
# The fire dates and recovery windows were set during PrepareData (fire
# severity + compute_adjusted_k_c) and stored in the event's FireMeta.csv /
# event.json. The simulation period is therefore read back from the context
# (fire end date -> end of the last recovery window) rather than hard-coded.
rain_data_start, rain_data_end = ctx.simulation_period()

# `num_years` is inferred from start/end (one API year per calendar
# year spanned).  `mean_annual_rainfall` and `average_temperature` are
# optional: leave them out of study.toml and they arrive here as None,
# which tells the backend service to estimate them from the catchment's
# lat/lon.  Set them in study.toml when you have site-specific climate
# statistics.
# The generated rainfall is cached under Ensembles/<ensemble>/ and reused
# on repeat runs — identical rainfall, no repeat API call. Pass
# regenerate=True to force a fresh draw.
# Note what that means for the two climate statistics: only the window and
# the replicate count decide whether the cache is reused, so changing
# mean_annual_rainfall or average_temperature after a run has no effect
# until you pass regenerate=True. You get the cached rainfall, silently.
replicates = get_rainfall_replicates(
    ctx,
    start=rain_data_start,
    end=rain_data_end,
    num_replicates=N_REPLICATES,
    mean_annual_rainfall=MEAN_ANNUAL_RAINFALL,   # None -> estimated
    average_temperature=AVERAGE_TEMPERATURE,     # None -> estimated
)
rainfall_data = replicates
