# %% [markdown]
# ## Erosion/RUSLE: Daily Simulation
#
# Erosion processed are modelled cell-by-cell, timestep-by-timestep.
#
# This can result in a large amount of output that in most cases is not directly usable.
#
#  The library currently multiple ways to extract data from the model as it runs via customisable 'recorders'.
#

# %%
# Grab a single rainfall sequence from the stochastic rainfall replicates and inspect it:
rain_seq = rainfall_30min.rainfall[:, INSPECT_REPLICATE].to_pandas()
rain_seq

# %% [markdown]
# ### Setting up recorders
#
# We want multiple gridded outputs:
# * Total erosion for the year following the fire (year 1),
# * Total erosion for the second year post fire
# * Peak 30 min erosion for year 1 and for year 2
# * The same stats for sediment *delivered* to streams
#
# We also want daily timeseries at the subcatchment scale that we can later import into Source. If you did not set `catchment.subcatchments` above, that timeseries covers the catchment as a single zone instead.

# %%
# Recorders are built with the default_rusle_recorders() factory: it returns
# a factory(ctx, start, end) that produces a fresh recorder set. Here we ask
# for whole-period ('total') grids of RUSLE and delivered sediment, each as a
# sum and a peak, plus a daily subcatchment timeseries. Other grid cadences
# are available: 'yearly', 'quarterly', 'monthly', 'weekly', 'daily',
# ('yearly', 'fire') for year-since-fire, or 'timestep' for a grid per model
# step. This produces keys like 'RUSLE_sum_total' and 'delivered_max_total'.
recorder_factory = rusle.default_rusle_recorders(
    grid_variables=('RUSLE', 'delivered'),
    grid_fns=('sum', 'max'),
    grid_timesteps=('total',),
    include_timeseries=True,
)
recorders = recorder_factory(ctx, rain_seq.index[0], rain_seq.index[-1])

# %%

