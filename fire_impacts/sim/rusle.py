def generate_rusle(
    rainfall:pd.Series,
    klscp:np.array,
    sdr:np.array,
    dnbr:np.array,
    cell_area_ha:float
    ):
    """
    Generator function that produces an iterable of (timestep, dict)
    tuples for each timestep entry in the provided rainfall data. Dict
    is a lookup of all relevant RUSLE results for that timestep.

    Parameters:
    - rainfall (pd.Series like): Series with 30-minute rainfall data.
    Must be DEPTH values in mm.
    - klscp (np.array): Raster layer with KLSCP values.
    - sdr (np.array): Raster layer with SDR values.
    - dnbr (np.array): Raster layer with dNBR values.
    - cell_area_ha (float): Area of each cell in hectares.

    Yields:
    - Tuple with timestep and dict with results like
    (timestep (datetime), dict with keys)
    - Dictionary has the following keys and value types:
        - 'total_rain' (float)
        - 'intensity' (float)
        - 'erosivity' (float)
        - 'RUSLE' (np.array)
        - 'SDR' (np.array)
        - 'RUSLE_below_threshold' (np.array)
        - 'RUSLE_above_threshold' (np.array)
        - 'SDR_below_threshold' (np.array)
        - 'SDR_above_threshold' (np.array))
    --------------------------------------------------------------------
    Notes:
    - This is a GENERATOR function which will return results as an
    iterable rather than one big dataset. Suits the use of recorders.
    - klscp, sdr and dnbr should have the same shape and transformation.
    --------------------------------------------------------------------
    """
    # Convert to Series if we've got a dataframe, to ensure consistency:
    if isinstance(rainfall, pd.DataFrame):
        rainfall = pd.Series(data=rainfall['rainfall'], index=rainfall.index)
    # Pre-compute severity masks based on dNBR thresholds
    dnbr_below_threshold = dnbr < DNBR_SEVERITY_THRESHOLD
    dnbr_above_threshold = dnbr >= DNBR_SEVERITY_THRESHOLD

    # Initialize timing variables for progress logging
    total_timesteps = len(rainfall.index)
    start_time = time.time()
    last_log_time = start_time
    iteration_count = 0

    # Loop over each 30-min timestep
    for timestep in rainfall.index:
        iteration_count += 1
        # Get rainfall amount (∆V_r) during the 30-min period
        delta_v_r = rainfall[timestep]

        # Initialize result dict
        result = {
            'total_rain': delta_v_r,
            'intensity': 0.0,
            'erosivity': 0.0,
            'RUSLE': np.zeros_like(klscp, dtype=np.float32),
            'SDR': np.zeros_like(klscp, dtype=np.float32),
            'RUSLE_below_threshold': np.zeros_like(klscp, dtype=np.float32),
            'RUSLE_above_threshold': np.zeros_like(klscp, dtype=np.float32),
            'SDR_below_threshold': np.zeros_like(klscp, dtype=np.float32),
            'SDR_above_threshold': np.zeros_like(klscp, dtype=np.float32),
        }

        # Skip calculations if delta_v_r is 0
        if delta_v_r == 0:
            yield (timestep, result)
            continue

        # Calculate rainfall intensity (∆V_r / ∆t_r)
        intensity = delta_v_r / 0.5  # mm/hr
        result['intensity'] = intensity

        # Calculate unit kinetic energy (e_r)
        e_r = 0.29 * (1 - 0.72 * np.exp(-EMPIRICAL_COEFFICIENT * intensity))

        # Calculate energy (E)
        E = e_r * delta_v_r

        # Calculate erosivity factor (R)
        R = E * intensity
        result['erosivity'] = R

        # Calculate RUSLE
        # TODO: sediment eroded? kg? t?
        RUSLE = (R * klscp) * cell_area_ha  # Total erosion in tonnes per hectare
        result['RUSLE'] = RUSLE

        # Calculate SDR_RUSLE
        # TODO: sediment delivered? kg? t?
        SDR_RUSLE = RUSLE * sdr  # Delivered erosion/sediment
        result['SDR'] = SDR_RUSLE

        # Apply severity masks
        result['RUSLE_below_threshold'] = np.where(dnbr_below_threshold, RUSLE, 0)
        result['RUSLE_above_threshold'] = np.where(dnbr_above_threshold, RUSLE, 0)
        result['SDR_below_threshold'] = np.where(dnbr_below_threshold, SDR_RUSLE, 0)
        result['SDR_above_threshold'] = np.where(dnbr_above_threshold, SDR_RUSLE, 0)

        # Check if LOG_INTERVAL_SECONDS have elapsed since last log
        current_time = time.time()
        if current_time - last_log_time >= LOG_INTERVAL_SECONDS:
            progress_pct = (iteration_count / total_timesteps) * 100
            elapsed_time = current_time - start_time
            avg_time_per_iteration = elapsed_time / iteration_count
            remaining_iterations = total_timesteps - iteration_count
            estimated_time_remaining = avg_time_per_iteration * remaining_iterations

            # Format time remaining as hours:minutes:seconds
            hours, remainder = divmod(int(estimated_time_remaining), 3600)
            minutes, seconds = divmod(remainder, 60)
            time_str = f"{hours:02d}:{minutes:02d}:{seconds:02d}" if hours > 0 else f"{minutes:02d}:{seconds:02d}"

            logger.info(
                f"Progress: {iteration_count}/{total_timesteps} timesteps "
                f"({progress_pct:.1f}%) - Current timestep: {timestep} - "
                f"Estimated time remaining: {time_str}"
            )
            last_log_time = current_time

        yield (timestep, result)

def generate_rusle_for_feature(geometry:list, rainfall:pd.DataFrame, klscp:np.array, sdr:np.array, dnbr:np.array, cell_area_ha:float, transform:Affine):
    '''
    Calculates RUSLE and SDR erosion values for sub-catchments based on rainfall simulations.

    Parameters:
    - geometry (list): List of shapely geometries representing the sub-catchment.
    - rainfall (pd.Series like): Series with 30-minute rainfall data.
    - klscp (np.array): Raster layer with KLSCP values.
    - sdr (np.array): Raster layer with SDR values.
    - dnbr (np.array): Raster layer with dNBR values.
    - cell_area_ha (float): Area of each cell in hectares.
    - transform (Affine): Affine transformation for the raster layers.

    klscp, sdr and dnbr should have the same shape and transformation.

    Yield:
    - Tuple with daily results for the sub-catchment:
      day (datetime), daily_total_rain (float), max_intensity (float), max_erosivity (float),
      daily_RUSLE (np.array), daily_SDR (np.array),
      daily_RUSLE_below_threshold (np.array), daily_RUSLE_above_threshold (np.array),
      daily_SDR_below_threshold (np.array), daily_SDR_above_threshold (np.array)
    '''
    mask = rasterio.features.rasterize(geometry, transform=transform, fill=np.nan, dtype=np.float32, out_shape=klscp.shape)
    klscp_masked = klscp*mask
    sdr_masked = sdr*mask
    dnbr_masked = dnbr*mask

    days = pd.Series(rainfall.index.date).drop_duplicates()
    for day in days:
        rainfall_data = rainfall[rainfall.index.date==day]
        # Initialize daily arrays for RUSLE and SDR_RUSLE
        daily_RUSLE = np.zeros_like(klscp_masked, dtype=np.float32)
        daily_SDR = np.zeros_like(klscp_masked, dtype=np.float32)
        daily_total_rain = 0.0
        max_intensity = 0.0
        max_erosivity = 0.0

        # Loop over each 30-min interval
        for subday in rainfall_data.values:
            # Get rainfall amount (∆V_r) during the 30-min period
            # delta_v_r = rainfall_data.sel(subday_30mins=subday).values
            delta_v_r = subday
            daily_total_rain+=delta_v_r

            # Skip calculations if delta_v_r is 0
            if delta_v_r == 0: # What if spatial? max?
                continue

            # Calculate rainfall intensity (∆V_r / ∆t_r)
            intensity = delta_v_r / 0.5  # mm/hr
            max_intensity = max(max_intensity,intensity)

            # Calculate unit kinetic energy (e_r)
            e_r = 0.29 * (1 - 0.72 * np.exp(-EMPIRICAL_COEFFICIENT * intensity))

            # Calculate energy (E)
            E = e_r * delta_v_r

            # Calculate erosivity factor (R)
            R = E * intensity
            max_erosivity = max(max_erosivity,R)

            # Calculate RUSLE
            # TODO: sediment eroded? kg? t?
            RUSLE = (R * klscp_masked) * cell_area_ha # Total erosion in tonnes per hectare
            daily_RUSLE += RUSLE  # Accumulate RUSLE for the day

            # Calculate SDR_RUSLE
            # TODO: sediment delivered? kg? t?
            SDR_RUSLE = RUSLE * sdr_masked  # Delivered erosion/sediment
            daily_SDR += SDR_RUSLE  # Accumulate SDR_RUSLE for the day


        # Mask daily_RUSLE and daily_SDR_RUSLE for dNBR values
        dnbr_below_threshold = dnbr_masked < DNBR_SEVERITY_THRESHOLD
        dnbr_above_threshold = dnbr_masked >= DNBR_SEVERITY_THRESHOLD

        daily_RUSLE_below_threshold = np.where(dnbr_below_threshold, daily_RUSLE, 0)
        daily_RUSLE_above_threshold = np.where(dnbr_above_threshold, daily_RUSLE, 0)

        daily_SDR_below_threshold = np.where(dnbr_below_threshold, daily_SDR, 0)
        daily_SDR_above_threshold = np.where(dnbr_above_threshold, daily_SDR, 0)

        yield((day,daily_total_rain,max_intensity,max_erosivity,daily_RUSLE,daily_SDR,daily_RUSLE_below_threshold,daily_RUSLE_above_threshold,daily_SDR_below_threshold,daily_SDR_above_threshold))

def compute_particulates(rusle_df,constituents_df=None):
    if constituents_df is None:
        constituents_df = load_package_data('ash_constituents.csv')

    # Iterate through each constituent and severity
    for _, row in constituents_df.iterrows():
        particulate = row['Particulate constituent (ash)']
        low_severity = row['Low severity- mean amount (mgkg-1)'] * MILLIGRAMS_TO_KILOGRAMS
        high_severity = row['High severity- mean amount (mgkg-1)'] * MILLIGRAMS_TO_KILOGRAMS

        # Define new column name
        column_name = f"{particulate} (Tonne)"
        rusle_df[column_name] = (rusle_df['RUSLE_SDR (Low severity)'] * low_severity) + (rusle_df['RUSLE_SDR (High severity)'] * high_severity)
    return rusle_df


