def record_subcatchment_timeseries(
    proj:FireImpactsProject,
    variable_name:str,
    fn="sum",
    label_field=None,
    agg_count=1
    ):
    """
    Build a RUSLE recorder that summarizes a variable over
    subcatchments

    Parameters:
    - proj (fire_impacts.FireImpactsProject): Current project
    - variable_name (str): Name of the variable to summarize.
    - fn (str): Summary function to use: 'sum', 'mean', 'max'. Default
    is 'sum'.
    - label_field (str): OPTIONAL: Field in the catchment boundaries to
    use as labels. If None, use the index.
    - agg_count (int): OPTIONAL: Number of timesteps to aggregate
    before recording. Default is 1

    Returns:
    - timeseries_recorder (function): A recorder function that can be
    used in the simulation (see: run_usle_simulation).
    --------------------------------------------------------------------
    Notes:
    - While the time series can always be resampled to a desired
    timestep AFTER the simulation, the agg_count parameter can be used
    to speed things up significantly by aggregating (sum) over multiple
    timesteps during the simulation itself.
    - agg_count would only be 1 if the value in the data was already in
    the desired time series interval i.e. if you were making a daily
    timeseries and had one 'row' per day in the data.
    --------------------------------------------------------------------
    """
    result = None
    index = None
    zones = None
    zone_names = None

    intermediate=None
    intermediate_count = 0
    ###########################################################################
    def timeseries_recorder(timestep,catchment,transform,**kwargs):
        """
        Primary closure function for building a timeseries of
        aggregated values.

        Parameters:
        - timestep:
        - catchment (str): Name of the catchment currently being worked
        with
        - transform: Rasterio transform object used for converting
        polygons to raster

        Returns:
        - None until the number of timesteps processed equals the
        requested number of aggregations, then a dictionary of arrays
        with one key:value pair for each zone.
        ----------------------------------------------------------------
        ----------------------------------------------------------------
        """
        # Declare the variables defined in the next function layer out
        #so this inner function will remember their values between
        #calls:
        # Row labels (index) and aggregated values (results) that will
        #be used to build the final dataframe:
        nonlocal result, index
        # The spatial zones, and their corresponding zone names, for
        #which aggregated values will be recorded in the timeseries.
        #Each zone will be a column in the final output with the zone
        #name as the column label:
        nonlocal zones, zone_names
        # intermediate will start as just the variable name, and then
        #it will be a string with a copy of the variable name for each
        #time this has been run (why?). intermediate_count is the
        #number of times this has happened.
        nonlocal intermediate, intermediate_count

        # kwargs here is a dictionary of some single values like 'total
        #rain' and 'erosivity', and some arrays for things like 'RUSLE'
        #and SDR.
        data = kwargs.get(variable_name)
        # Throw an error if variable name hasn't been provided:
        if data is None:
            raise ValueError(
                f"Variable {variable_name} not found in simulation data."
                )
        # If zones haven't been provided, we still need an area for
        #consistent behaviour:
        if zones is None:
            # Zone each subcatchment separately; fall back to the
            # catchment boundary as a single zone when no subcatchments
            # have been registered for the catchment.
            try:
                boundaries_v = proj.get_subcatchments(catchment)
            except FileNotFoundError:
                boundaries_v = proj.catchment_boundary(catchment)
            resolved_label = label_field
            if resolved_label is None:
                resolved_label = proj.subcatchment_label_field(catchment)
            # List method to build an array of rasters the same shape
            #as the catchment boundary:
            zones = [
                rasterio.features.rasterize(
                    [g], # The geometry (see 'for g in ...')
                    transform=transform,
                    fill=np.nan,
                    dtype=np.float32,
                    out_shape=data.shape
                    ) for g in boundaries_v.geometry
                ]
            if resolved_label is None:
                zone_names = boundaries_v.index.values
            elif resolved_label not in boundaries_v.columns:
                logger.warning(
                    "Subcatchment label field '%s' is configured for "
                    "catchment '%s' but is not present in the saved "
                    "subcatchments shapefile (columns: %s). Falling "
                    "back to integer indices. Re-run "
                    "FireImpactsProject.add_subcatchments(..., "
                    "label_field='%s') to rewrite the shapefile with "
                    "the label column retained.",
                    resolved_label, catchment,
                    list(boundaries_v.columns), resolved_label,
                )
                zone_names = boundaries_v.index.values
            else:
                zone_names = boundaries_v[resolved_label].values

        # Update the counter for the number of times this has been run:
        intermediate_count += 1
        if intermediate is None:
            intermediate = data
        else:
            # Data and intermediate are both arrays; intermediate is
            #the aggregation of all timesteps already recorded in the
            #current cycle, and data is the single values for the
            #new timestep currently being processed.
            # Note that these are 3D arrays, so when you add data to
            #intermediate it adds a new 2D array of the current set of
            #values, along the third dimension.
            intermediate += data

        # If we haven't yet reached the requested number of timesteps,
        #we haven't yet changed result so it will still be None.
        if intermediate_count < agg_count:
            return result
        # Once we've reached the requested agg count, store the whole
        #3D array as data and update intermediates to their starting
        #values.
        else:
            data = intermediate
            intermediate = None
            intermediate_count = 0
        # If there's not already an index specified, make an empty list
        #so we still have something to use:
        if index is None:
            index = []
        # Add the current timestep as the index value:
        index.append(timestep)

        # Make a copy of the set of arrays for each zone, where all the
        #values (cells) outside that zone will be NaN and those inside
        #will retain their values.
        masked = [data * zone for zone in zones]

        def agg(d):
            """
            Helper function to handle the requested aggregation
            """
            if fn == "sum":
                return np.nansum(d)
            elif fn == "mean":
                return np.nanmean(d)
            elif fn == "max":
                return np.nanmax(d)
            else:
                raise ValueError(f"Function {fn} not recognized.")

        # If there's not already a result, make a dictionary with a
        #list for every AoI:
        if result is None:
            result = {name: [] for name in zone_names}

        # For each zone-specific set of arrays, apply the requested
        #aggregation:
        grouped = [agg(d) for d in masked]
        # Using enumerate() on zone_names simply gives us an iterable
        #with a number for each zone name:
        for ix,name in enumerate(zone_names):
            # The key in result will be the zone name. The value will
            #be the array in grouped that is in the same position as
            #the current zone in zones.
            result[name].append(grouped[ix])

        return result

    ###########################################################################
    def reset():
        """
        Secondary closure function to revert all encapsulated variables
        to starting values.
        """
        # Access the encapsulated variables from the outer function:
        nonlocal result, index
        nonlocal zones, zone_names
        nonlocal intermediate, intermediate_count
        # Reset them all to their starting values:
        index = None
        zones = None
        zone_names = None
        result = None
        intermediate = None
        intermediate_count = 0

    ###########################################################################
    def finalize():
        """
        Secondary closure function
        """
        # Access the up-to-date result and index variables:
        nonlocal result, index
        # Go through each zone in the result dictionary and convert
        #the data to a numpy array (was it already one??)
        for key in result:
            result[key] = np.array(result[key])

        # Convert to a dataframe and return:
        return pd.DataFrame(result,index=index)

    # Add the two secondary closure functions as method-like
    #attachments to the main one
    timeseries_recorder.reset = reset
    timeseries_recorder.finalize = finalize
    return timeseries_recorder

