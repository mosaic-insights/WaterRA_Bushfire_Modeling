def run_usle_simulation(
    project:FireImpactsProject,
    rainfall,
    catchment=None,
    recorders=None,
    save_rasters:bool=True,
    save_timeseries:bool=True
    ):
    """
    Run the USLE simulation for a given project and rainfall data,
    recording results as specified.

    Parameters:
    - project (fire_impacts.FireImpactsProject): Current project
    - rainfall (Series-like): 30 minute rainfall data (mm)
    - catchment (str): Name of the catchment to process. If None,
    process all catchments.
    - recorders (dict): OPTIONAL: Dictionary of recorder functions to
    use during the simulation.
    - save_rasters (bool): Whether the output rasters should be saved 
    as GeoTIFF files to the results folder for the current catchment
    - save_timeseries (bool): Whether the daily timeseries should be 
    saved as a csv file to the results folder for the current catchment

    Returns:
    - results (dict): Dictionary of recorded results from the
    simulation.
    - params (tuple): Tuple of parameters used in the simulation
    (klscp, sdr, dnbr, cell_area_ha, transform).
    --------------------------------------------------------------------
    Notes:
    - Each recorder function should accept parameters
    (timestep, **data) and return recorded results.
    - The data dictionary passed to each recorder will contain keys
    such as 'RUSLE', 'SDR', etc.
    - Each recorder function should also have 'reset' and 'finalize'
    methods to manage state.
    --------------------------------------------------------------------
    """
    if catchment is None:
        return project.for_each_catchment(
            lambda c: run_usle_simulation(project,rainfall,c,recorders)
            )
    # If no recorders were passed, use an empty dictionary so the rest
    #of the code works consistently:
    if recorders is None:
        recorders = dict()
    # Reset each recorder so we're building new arrays for aggregation:
    for recorder in recorders.values():
        recorder.reset()

    # Get the relevant RUSLE parameters as handy arrays:
    params = _rusle_parameter_grids(project,catchment)
    klscp, sdr, dnbr, cell_area_ha, transform = params
    # Get the catchment boundary geometry in a form that's usable by
    #rasterio:
    catchment_boundary = project.catchment_boundary(catchment)
    # catchment_boundary = project.get_subcatchments(catchment).dissolve()
    geometry = catchment_boundary.geometry.values

    # Convert the catchment boundary to a raster with 1 for every cell
    #that's within the catchment boundary, and NaN for all others:
    mask = rasterio.features.rasterize(
        geometry,
        transform=transform,
        fill=np.nan,
        dtype=np.float32,
        out_shape=klscp.shape
        )

    # Use the mask to convert all values in the RUSLE grids that are
    #outside the catchment boundary to NaN:
    klscp_masked = klscp*mask
    sdr_masked = sdr*mask
    dnbr_masked = dnbr*mask

    # Empty dictionary to start filling with results:
    results = dict()
    # Iterate over each tuple of (timestep, values dict) produces by
    #the generate_rusle() generator function:
    for ts_data in generate_rusle(
        rainfall,
        klscp_masked,
        sdr_masked,
        dnbr_masked,
        cell_area_ha
        ):
        # Unpack the tuple elements:
        timestep, data = ts_data
        # Go through each encapsulating recorder function and load
        #the rusle data in for the current tuple:
        for key, recorder in recorders.items():
            results[key] = recorder(
                timestep,
                **data, # Unpack all values in the data dictionary
                catchment=catchment,
                transform=transform # from _rusle_parameter_grids() above
                )

    # Now that we've gone through all timesteps in the rainfall data,
    #get the final result. In the case of catchment timeseries, this
    #is a dataframe of the values aggregated for each of the specified
    #number of timesteps (48 for daily aggregation on half-hourly data).
    for key, recorder in recorders.items():
        results[key] = recorder.finalize()

    if save_rasters:
        template_raster = project.catchment_path(
            catchment,
            'Erodibility',
            'LS_factor.tif'
            )
        _, template_meta = read_raster(template_raster)
        for output_raster in c.RUSLE_OUTPUT_RASTER_NAMES:
            save_data = results[output_raster]
            save_catchment_raster(
                project=project,
                catchment_name=catchment,
                file_name=output_raster,
                section=c.RESULTS_FOLDER_NAME,
                data=save_data,
                meta=template_meta
                )

    if save_timeseries:
        out_name = project.catchment_path(
            catchment,
            c.RESULTS_FOLDER_NAME,
            c.RUSLE_OP_TIMESERIES_NAME + '.csv'
            )
        results[c.RUSLE_OP_TIMESERIES_NAME].to_csv(out_name)

    # Attach a pointer to all the rusle parameters (mostly grids) used
    #for these calcs:
    results['params'] = params

    return results

