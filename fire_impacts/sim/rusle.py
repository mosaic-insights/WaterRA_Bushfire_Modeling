def compute_klscp_layer(
    proj:FireImpactsProject,
    catchment:str,
    support_practice_factor:float=1.0
    ):
    """
    Using previously-generated C, K, and LS factor rasters, generate
    a raster layer of the KLSCP values for the catchment.

    Returns: None

    Writes: A KLSCP raster (.tif) to the Erodibility folder of the
    current project/catchment.
    --------------------------------------------------------------------
    --------------------------------------------------------------------
    """
    # Read all input rasters and ensure they align:
    c_factor_path = proj.catchment_path(
        catchment,
        'Erodibility','C_factor_adjusted.tif'
        )
    k_factor_path = proj.catchment_path(
        catchment,
        'Erodibility',
        'K_factor_adjusted.tif'
        )
    ls_factor_path = proj.catchment_path(
        catchment,
        'Erodibility',
        'LS_factor.tif'
        )

    # Calculate values for the new layer and write them to a new raster:
    with rasterio.open(c_factor_path) as c_factor, \
         rasterio.open(k_factor_path) as k_factor, \
         rasterio.open(ls_factor_path) as ls_factor:

        # Read data as arrays
        c_array = c_factor.read(1)
        k_array = k_factor.read(1)
        ls_array = ls_factor.read(1)

        # Copy the profile metadata before exiting the `with` block.
        #We pick a layer where the nodata value is np.nan:
        new_meta_profile = ls_factor.meta.copy()

        # Perform the multiplication for RUSLE base layer
        base = c_array * k_array * ls_array
        base = base * support_practice_factor

        # Save the result as a raster layer
        base_raster_path = proj.catchment_path(
            catchment,
            'Erodibility',
            'KLSCP.tif'
            )
        # Update the metadata:
        new_meta_profile.update(
            dtype=rasterio.float32,
            count=1,
            compress='lzw'
            )

        # Write the new array with the new metadata to the relevant
        #project folder:
        with rasterio.open(base_raster_path, 'w', **new_meta_profile) as dst:
            dst.write(base, 1)

###############################################################################
def _rusle_parameter_grids(project:FireImpactsProject, catchment:str):
    """
    Organise relevant raster parameters and return them as usable
    data objects ready for rusle calculations.

    Parameters:
    - project (FireImpactsProject object): The current project, which
    should already have the relevant rasters saved in its directories.
    - catchment (string): Name of the catchment to get the grids for.

    Returns:
    - The data ONLY (as an array), for KLSCP, SDR, and DNBR.
    - The cell area (in hectares) and the raster transform object,
    which should be usable by all three data arrays.
    --------------------------------------------------------------------
    --------------------------------------------------------------------
    """
    cell_area_m2 = project.cell_area(catchment)
    cell_area_ha = cell_area_m2 * M2_TO_HA  # Convert to hectares

    # Generate a KLSCP raster to simplify analysis:
    compute_klscp_layer(project,catchment)

    # Now read that raster into memory:
    klscp, klscp_meta = read_raster(
        project.catchment_path(
            catchment,
            'Erodibility',
            'KLSCP.tif'
            )
        )

    transform = klscp_meta['transform']
    crs = klscp_meta['crs']

    # Get the Sediment Delivery Ratio (SDR) raster, which is generated
    #ultimately by the calculate_lumped_rusle() function in this module:
    sdr,_ = read_raster(
        project.catchment_path(
            catchment,
            'Delivery',
            'SDR.tif'
            )
        )

    # Get the delta Normalised Burn Ratio (dNBR) raster, which is
    #generated by severity.calculate_fire_severity(). Use read_aligned
    #to ensure it's in the same CRS as the RUSLE layers.
    # Do we need to do this? Why don't we do it for SDR too?
    dnbr = read_aligned(
        project.catchment_path(
            catchment,
            'FireSeverity',
            'masked_dNBR.tif'
            ),
        transform,
        crs,
        klscp.shape
        )
    return klscp, sdr, dnbr, cell_area_ha, transform

