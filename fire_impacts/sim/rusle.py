def record_summary_grid(variable,fn='sum',start_time=None,end_time=None):
    '''
    Build a RUSLE recorder that summarizes a grid variable over time.

    Parameters:
    - variable (str): Name of the variable to summarize.
    - fn (str): Summary function to use: 'sum', 'mean', 'max'. Default is 'sum'.
    - start_time (datetime): OPTIONAL: Start time for the summary. If None, use the start of the simulation.
    - end_time (datetime): OPTIONAL: End time for the summary. If None, use the end of the simulation.
    Returns:
    - grid_recorder (function): A recorder function that can be used in the simulation (see: run_usle_simulation).
    '''
    result = None
    count = 0
    def grid_recorder(timestep,**kwargs):
        nonlocal result, count
        count += 1
        if start_time is not None and timestep < start_time:
            return result
        if end_time is not None and timestep > end_time:
            return result

        data = kwargs[variable]
        if result is None:
            result = data
        elif fn=='max':
            result = np.maximum(result, data)
        else:  # sum or mean
            result += data
        if fn=='mean':
            return result / count

        return result

    def reset():
        nonlocal result, count
        result = None
        count = 0

    def finalize():
        nonlocal result, count
        if fn=='mean':
            return result / count
        return result
    grid_recorder.reset = reset
    grid_recorder.finalize = finalize

    return grid_recorder

